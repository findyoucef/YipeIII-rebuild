using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Yipe.Desktop;

// Reuses the 5x7 glyphs in app/main.cpp. No system font or external font license is needed.
internal sealed class PixelFont : IDisposable
{
    private readonly Texture2D texture;

    public PixelFont(GraphicsDevice device)
    {
        texture = new Texture2D(device, 96 * 6, 8);
        var pixels = new Color[texture.Width * texture.Height];
        for (var character = 32; character < 128; character++)
        {
            var rows = Glyph(char.ToUpperInvariant((char)character));
            for (var y = 0; y < rows.Length; y++)
                for (var x = 0; x < 5; x++)
                    if ((rows[y] & (1 << (4 - x))) != 0)
                        pixels[y * texture.Width + (character - 32) * 6 + x] = Color.White;
        }
        texture.SetData(pixels);
    }

    public void Draw(SpriteBatch batch, string text, int x, int y, Color color, int scale = 1)
    {
        var cursor = x;
        foreach (var character in text)
        {
            if (character == '\n') { cursor = x; y += 11 * scale; continue; }
            var ascii = character is >= ' ' and <= '~' ? character : '?';
            batch.Draw(texture, new Rectangle(cursor, y, 5 * scale, 7 * scale),
                new Rectangle((ascii - 32) * 6, 0, 5, 7), color);
            cursor += 6 * scale;
        }
    }

    public void Dispose() => texture.Dispose();

