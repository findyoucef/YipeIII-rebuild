#!/usr/bin/env python3
"""Execute only the retained C++ route's input-building block to export its inputs.

No gameplay or expected result is generated by this script. The compiled reference
application supplies expected checkpoints separately. Run from any directory.
"""
import json
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
source = (root / 'tests/app_shortcut_tests.cpp').read_text()
start = source.index('        const auto walk_route =')
end = source.index('        status_bar_visible = true;', start)
block = source[start:end]
for statement in ('SDL_FlushEvents(SDL_FIRSTEVENT, SDL_LASTEVENT);', 'route_combat = true;', 'messages.clear();', 'message_texts.clear();'):
    block = block.replace(statement, '')
keys = {'KP_1': '1', 'DOWN': '2', 'KP_3': '3', 'LEFT': '4', 'RIGHT': '6', 'KP_7': '7', 'UP': '8', 'KP_9': '9', 'F5': 'checkpoint', 'i': 'inventory', 'c': 'spells', 'o': 'other'}
prelude = r'''
#include <deque>
#include <iomanip>
#include <iostream>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>
struct Choice { std::string title; int button; std::string text; };
std::deque<Choice> dialog_choices;
struct Command { std::string key; int ticks = 0; };
std::vector<Command> commands;
void push_key(std::string key) { commands.push_back({key}); }
void push_wait(int ticks) { commands.push_back({"wait", ticks}); }
void require(bool condition, const char* message) { if (!condition) throw std::runtime_error(message); }
struct SDL_Event { int type; struct { struct { std::string sym; int mod; } keysym; } key; };
constexpr int SDL_KEYDOWN=1, KMOD_CTRL=1, KMOD_SHIFT=2;
int SDL_PushEvent(const SDL_Event* event) { push_key(event->key.keysym.sym); return 1; }
'''
prelude += '\n'.join(f'const std::string SDLK_{key}={json.dumps(value)};' for key, value in keys.items())
ending = r'''
 push_key("checkpoint");
 std::cout << "{\"commands\":[";
 bool first=true;
 for (const auto& command:commands) {
  if(!first)std::cout<<',';first=false;
  std::cout<<'['<<std::quoted(command.key)<<','<<command.ticks<<']';
 }
 std::cout<<"],\"choices\":[";first=true;
 for(const auto& choice:dialog_choices) {
  if(!first)std::cout<<',';first=false;
  std::cout<<'['<<std::quoted(choice.title)<<','<<choice.button<<','<<std::quoted(choice.text)<<']';
 }
 std::cout<<"]}\n";
}
'''
with tempfile.TemporaryDirectory(prefix='yipe-opening-inputs-') as directory:
    cpp = Path(directory) / 'inputs.cpp'
    exe = Path(directory) / 'inputs'
    cpp.write_text(prelude + '\nint main() {\n' + block + ending)
    subprocess.run(['c++', '-std=c++20', '-Wall', '-Wextra', '-Werror', str(cpp), '-o', str(exe)], check=True)
    data = json.loads(subprocess.check_output([str(exe)]), strict=False)
output = root / 'monogame/Yipe.Tests/Fixtures/Opening/inputs.json'
output.write_text(json.dumps(data, indent=2) + '\n')
print(f'{len(data["commands"])} commands; {len(data["choices"])} choices; {sum(c[0] == "checkpoint" for c in data["commands"])} checkpoints')
