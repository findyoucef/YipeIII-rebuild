#!/usr/bin/env python3
"""Recover the 28 Help and Info pages selected by 0x00413d90."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--strings", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    strings = {}
    for line in args.strings.read_text().splitlines():
        resource = json.loads(line)
        if resource["language"] != 1033:
            continue
        if resource["id"] in strings:
            raise ValueError(f"duplicate resource string {resource['id']}")
        strings[resource["id"]] = resource["value"]

    rows = []
    for page in range(28):
        title = strings[901 + page]
        body = strings[801 + page]
        if not title or not body:
            raise ValueError(f"empty help page {page + 1}")
        # Escape question marks so the original '?????' does not trigger
        # trigraph diagnostics in C++ compilers.
        rows.append("    {" + json.dumps(title, ensure_ascii=False).replace("?", r"\?")
                    + ",\n     "
                    + json.dumps(body, ensure_ascii=False).replace("?", r"\?") + "},")
    output = """// Generated by tools/extract_help.py; do not edit manually.
// Dialog 276: titles 901-928 and bodies 801-828, in the original page order.
#pragma once

#include <array>
#include <string_view>
#include <utility>

namespace yipe {
inline constexpr std::array<std::pair<std::string_view, std::string_view>, 28>
original_help_pages{{
""" + "\n".join(rows) + "\n}};\n} // namespace yipe\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output)


if __name__ == "__main__":
    main()
