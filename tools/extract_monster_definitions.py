#!/usr/bin/env python3
"""Recover Yipe! III's monster stat table and resource identities."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


MONSTER_COUNT = 41


def parse_number(value: str) -> int:
    return int(value, 0)


def load_resource_strings(path: Path) -> dict[int, str]:
    strings: dict[int, str] = {}
    with path.open(encoding="utf-8") as source:
        for line in source:
            record = json.loads(line)
            strings[int(record["id"])] = str(record["value"])
    return strings


def extract(
    stats_path: Path, damage_path: Path, strings_path: Path
) -> list[dict[str, object]]:
    stats_text = stats_path.read_text(encoding="utf-8")
    stat_values = {
        parse_number(index): parse_number(value)
        for index, value in re.findall(
            r"local_348\[(0x[0-9a-fA-F]+|\d+)\]\s*=\s*"
            r"(0x[0-9a-fA-F]+|\d+)\s*;",
            stats_text,
        )
    }
    damage_text = damage_path.read_text(encoding="utf-8")
    damage_values = {
        parse_number(index): parse_number(value)
        for index, value in re.findall(
            r"local_16c\[(0x[0-9a-fA-F]+|\d+)\]\s*=\s*"
            r"(0x[0-9a-fA-F]+|\d+)\s*;",
            damage_text,
        )
    }
    strings = load_resource_strings(strings_path)

    monsters = []
    for type_id in range(1, MONSTER_COUNT + 1):
        indexes = {
            "health_base": type_id,
            "rank_and_health_range": type_id + 0x7E,
            "attack_base": type_id + 0x2A,
            "defense_base": type_id + 0x54,
            "special_rating": type_id + 0xA8,
        }
        missing = [name for name, index in indexes.items() if index not in stat_values]
        if missing:
            raise ValueError(f"monster {type_id} is missing fields: {', '.join(missing)}")
        minimum_damage_index = type_id * 2
        maximum_damage_index = minimum_damage_index + 1
        if minimum_damage_index not in damage_values or maximum_damage_index not in damage_values:
            raise ValueError(f"monster {type_id} is missing its damage range")
        minimum_damage = damage_values[minimum_damage_index]
        maximum_damage = damage_values[maximum_damage_index]
        if minimum_damage > maximum_damage:
            raise ValueError(f"monster {type_id} has an invalid damage range")
        string_id = type_id + 229
        if string_id not in strings:
            raise ValueError(f"monster {type_id} is missing string resource {string_id}")
        monsters.append(
            {
                "type_id": type_id,
                "name": strings[string_id],
                "string_resource_id": string_id,
                "bitmap_resource_id": type_id + 173,
                **{name: stat_values[index] for name, index in indexes.items()},
                "damage_minimum": minimum_damage,
                "damage_maximum": maximum_damage,
            }
        )
    return monsters


def render_cpp(monsters: list[dict[str, object]]) -> str:
    lines = [
        "// Generated by tools/extract_monster_definitions.py. Do not edit by hand.",
        '#include "yipe/encounter.hpp"',
        "",
        "#include <array>",
        "#include <optional>",
        "",
        "namespace yipe {",
        "namespace {",
        "",
        f"constexpr std::array<MonsterDefinition, {len(monsters)}> definitions{{{{",
    ]
    for monster in monsters:
        name = json.dumps(monster["name"], ensure_ascii=True)
        lines.append(
            "    {"
            f"{monster['type_id']}, {name}, {monster['string_resource_id']}, "
            f"{monster['bitmap_resource_id']}, {monster['health_base']}, "
            f"{monster['rank_and_health_range']}, {monster['attack_base']}, "
            f"{monster['defense_base']}, {monster['special_rating']}, "
            f"{monster['damage_minimum']}, {monster['damage_maximum']}"
            "},"
        )
    lines.extend(
        [
            "}};",
            "",
            "} // namespace",
            "",
            "std::optional<MonsterDefinition> original_monster_definition(int type_id) {",
            "    if (type_id < 1 || type_id > static_cast<int>(definitions.size())) {",
            "        return std::nullopt;",
            "    }",
            "    return definitions[static_cast<std::size_t>(type_id - 1)];",
            "}",
            "",
            "} // namespace yipe",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stats-source", type=Path, required=True)
    parser.add_argument("--damage-source", type=Path, required=True)
    parser.add_argument("--strings", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--cpp-output", type=Path, required=True)
    arguments = parser.parse_args()

    monsters = extract(arguments.stats_source, arguments.damage_source, arguments.strings)
    result = {
        "format": "yipe3-original-monster-definitions-v2",
        "source_function": "00405640",
        "damage_source_function": "004042e0",
        "monsters": monsters,
    }
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    arguments.cpp_output.parent.mkdir(parents=True, exist_ok=True)
    arguments.cpp_output.write_text(render_cpp(monsters), encoding="utf-8")


if __name__ == "__main__":
    main()
