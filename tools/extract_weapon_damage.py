#!/usr/bin/env python3
"""Recover Yipe! III's 42 weapon damage ranges from static disassembly."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path


FUNCTION_START = 0x417AB0
FUNCTION_END = 0x417D90
WEAPON_COUNT = 42


def parse_number(value: str) -> int:
    return int(value, 0)


def disassemble(executable: Path, objdump: Path) -> str:
    result = subprocess.run(
        [
            str(objdump),
            "-d",
            "--no-show-raw-insn",
            f"--start-address={FUNCTION_START:#x}",
            f"--stop-address={FUNCTION_END:#x}",
            str(executable),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def extract_ranges(text: str) -> list[tuple[int, int]]:
    registers: dict[str, int] = {}
    stack: dict[int, int] = {}

    for line in text.splitlines():
        match = re.match(r"^\s*[0-9a-fA-F]+:\s+(.+?)\s*$", line)
        if not match:
            continue
        instruction = match.group(1)

        immediate_register = re.fullmatch(
            r"movl\s+\$(0x[0-9a-fA-F]+|\d+),\s*%(eax|ebx|ecx|edx|esi|edi|ebp)",
            instruction,
        )
        if immediate_register:
            registers[immediate_register.group(2)] = parse_number(
                immediate_register.group(1)
            )
            continue

        register_stack = re.fullmatch(
            r"movl\s+%(eax|ebx|ecx|edx|esi|edi|ebp),\s*"
            r"(0x[0-9a-fA-F]+|\d+)\(%esp\)",
            instruction,
        )
        if register_stack:
            register = register_stack.group(1)
            if register not in registers:
                raise ValueError(f"stack write uses unknown register %{register}")
            stack[parse_number(register_stack.group(2))] = registers[register]
            continue

        immediate_stack = re.fullmatch(
            r"movl\s+\$(0x[0-9a-fA-F]+|\d+),\s*"
            r"(0x[0-9a-fA-F]+|\d+)\(%esp\)",
            instruction,
        )
        if immediate_stack:
            stack[parse_number(immediate_stack.group(2))] = parse_number(
                immediate_stack.group(1)
            )

    ranges = []
    for weapon_rank in range(1, WEAPON_COUNT + 1):
        minimum_offset = 8 + weapon_rank * 8
        maximum_offset = minimum_offset + 4
        if minimum_offset not in stack or maximum_offset not in stack:
            raise ValueError(f"weapon rank {weapon_rank} is missing its damage range")
        minimum = stack[minimum_offset]
        maximum = stack[maximum_offset]
        if minimum > maximum:
            raise ValueError(f"weapon rank {weapon_rank} has an invalid damage range")
        ranges.append((minimum, maximum))
    return ranges


def render_cpp(ranges: list[tuple[int, int]]) -> str:
    lines = [
        "// Generated by tools/extract_weapon_damage.py. Do not edit by hand.",
        '#include "yipe/encounter.hpp"',
        "",
        "#include <array>",
        "#include <utility>",
        "",
        "namespace yipe {",
        "namespace {",
        "",
        f"constexpr std::array<std::pair<int, int>, {len(ranges)}> ranges{{{{",
    ]
    lines.extend(f"    {{{minimum}, {maximum}}}," for minimum, maximum in ranges)
    lines.extend(
        [
            "}};",
            "",
            "} // namespace",
            "",
            "std::pair<int, int> original_weapon_damage_range(int weapon_rank) {",
            "    if (weapon_rank < 1 || weapon_rank > static_cast<int>(ranges.size())) {",
            "        return {0, 1};",
            "    }",
            "    return ranges[static_cast<std::size_t>(weapon_rank - 1)];",
            "}",
            "",
            "} // namespace yipe",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--executable", type=Path, required=True)
    parser.add_argument("--objdump", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--cpp-output", type=Path, required=True)
    arguments = parser.parse_args()

    ranges = extract_ranges(disassemble(arguments.executable, arguments.objdump))
    result = {
        "format": "yipe3-original-weapon-damage-v1",
        "source_function": "00417ab0",
        "invalid_rank_fallback": {
            "damage_minimum": 0,
            "damage_maximum": 1,
        },
        "weapons": [
            {
                "weapon_rank": weapon_rank,
                "damage_minimum": minimum,
                "damage_maximum": maximum,
            }
            for weapon_rank, (minimum, maximum) in enumerate(ranges, start=1)
        ],
    }
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    arguments.cpp_output.parent.mkdir(parents=True, exist_ok=True)
    arguments.cpp_output.write_text(render_cpp(ranges), encoding="utf-8")


if __name__ == "__main__":
    main()
